// The map of the Ember Reach: where each of its 24 systems sits and what part it plays.
//
// The cluster is a flattened disc about 42 by 38 light-years (45 between its two farthest stars).
// Its structure is authored, not rolled:
//
//   * a dense, contested CORE of six systems around Tallow, the start;
//   * three ARMS, one per great power, each joined to the core through a single gate system
//     (the only link shorter than 7 ly) and ending in an unclaimed frontier system;
//   * the BADLANDS road, a lawless back way from the core's rough end to the League arm that
//     passes the outlaw haven Falselight;
//   * Afterglow, a dead star on a spur of its own.
//
// Six slots name a hand-authored showpiece (see index.ts). The other eighteen are generated by
// sim/universe.ts from the hints given here; the galaxy seed decides their names, worlds and
// people, and nudges their positions by a fraction of a light-year.

import type { EconomyType, PowerId } from '../../core/types';

export const START_SYSTEM_ID = 'tallow';
export const START_STATION_ID = 'tallow.st.chandlers-wheel';

/** Kind of primary star a generated system gets. */
export type StarHint = 'M' | 'Mlate' | 'K' | 'G' | 'F' | 'brownDwarf';

/**
 * The world people live on (or would):
 *  eyeball – a tide-locked temperate world in a red dwarf's habitable zone
 *  garden  – a turning terran or ocean world under a brighter star
 *  harsh   – a desert or cold rock worked for what is in it
 *  ice     – an ice moon or frozen planet; the system has a giant
 *  wild    – nothing promised (uninhabited frontier)
 */
export type WorldHint = 'eyeball' | 'garden' | 'harsh' | 'ice' | 'wild';

export type Region = 'core' | 'assembly' | 'hegemony' | 'league' | 'badlands' | 'frontier';

export interface GalaxySlot {
  /** Stable key (seeds the generator for this slot). */
  key: string;
  /** Id of the hand-authored system that fills this slot, if any. */
  showcase?: string;
  /** Position, light-years. */
  pos: [number, number, number];
  region: Region;
  /** Power that dominates the system's politics; null where none does. */
  power: PowerId | null;
  star: StarHint;
  world: WorldHint;
  /** 0 uninhabited, 1 a few outposts, 2 towns, 3 a hub of millions. */
  tier: 0 | 1 | 2 | 3;
  /** Number of stations (0 for uninhabited systems). */
  stations: number;
  /** Baseline security 0..1. */
  security: number;
  /** Primary economy of the capital station, when the system has a speciality. */
  economy?: EconomyType;
  /** First sentence of the system description; `{name}` is replaced by the system's name. */
  role: string;
}

const showcase = (key: string, pos: [number, number, number], region: Region, power: PowerId | null, security: number): GalaxySlot => ({
  key,
  showcase: key,
  pos,
  region,
  power,
  star: 'M',
  world: 'wild',
  tier: 3,
  stations: 0,
  security,
  role: '',
});

