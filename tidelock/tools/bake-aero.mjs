#!/usr/bin/env node
// Bake the hull aero/thermal skin tables (SIMULATION.md W2-B item 4) at BUILD time into src/data/aero/<hull>.ts.
//
//   node tools/bake-aero.mjs              bake the Wren (the only hull that flies in air today)
//   node tools/bake-aero.mjs --hull <id>  another hull (writes src/data/aero/<id>.ts)
//   node tools/bake-aero.mjs --out <dir>  write elsewhere (scratch runs)
//
// The pass itself is tools/aeroBake.ts (bundled for node with esbuild): Newtonian force and moment on a 33×33
// mirror-halved octahedral vertex grid; free-molecular terms, analytic damping derivatives and the 12 zone projected
// areas on its 17×17 subgrid; shadowing by rays against the hull compound. Output: int16 per column with a
// per-column scale, base64 in a .ts module, decoded once at load by src/world/aero.ts (decodeAero). The bytes are
// deterministic (no randomness, fixed order), so the table is identical on every engine.
//
// When to re-run: after src/data/hullColliders.ts changes (and once W2-C's HULL_ZONES lands: switch zoneOf in
// tools/aeroBake.ts to it). tests/aero.test.ts re-bakes sample directions and fails if the file is stale.
// Not called by build.mjs (W2-B's wiring may add `--if-stale` there; the bake takes a few seconds in node).

import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const hull = arg('--hull', 'wren');
const outDir = path.resolve(arg('--out', path.join(root, 'src/data/aero')));

function b64(bytes) {
  return Buffer.from(bytes.buffer, bytes.byteOffset, bytes.byteLength).toString('base64');
}

const { build } = await import('esbuild');
const tmp = path.join(os.tmpdir(), `tidelock-aero-${process.pid}.mjs`);
await build({
  stdin: { contents: "export * from './tools/aeroBake';", resolveDir: root, loader: 'ts' },
  bundle: true, platform: 'node', format: 'esm', outfile: tmp, logLevel: 'error',
});
const B = await import(pathToFileURL(tmp).href);
await fs.unlink(tmp).catch(() => {});

const r = B.bakeHull(hull);
const qb = B.quantise(r.big, B.COLS_BIG), qs = B.quantise(r.small, B.COLS_SMALL);
// little-endian int16 bytes (Int16Array is platform-endian; every target is little-endian, checked at decode)
const fmt = (a) => a.map((x) => Number(x.toPrecision(9))).join(', ');
const name = `AERO_${hull.toUpperCase()}`;
const src = `// GENERATED by tools/bake-aero.mjs from src/data/hullColliders.ts (${hull}) — do not edit; re-run the tool.
// Newtonian / free-molecular / damping / zone tables for src/world/aero.ts (decodeAero). See tools/aeroBake.ts.
// ${r.samples} skin cells at ${r.spacing} m, skin ${r.skinArea.toFixed(1)} m², volume ${r.volume.toFixed(1)} m³.
// Zones are PROVISIONAL (tools/aeroBake.ts ZONES) until W2-C's HULL_ZONES lands.

export const ${name} = {
  version: 1,
  hull: '${hull}',
  nBig: ${B.N_BIG},
  nSmall: ${B.N_SMALL},
  colsBig: ${B.COLS_BIG},
  colsSmall: ${B.COLS_SMALL},
  cpMax: ${B.CP_MAX},
  cf: ${B.C_F},
  samples: ${r.samples},
  skinArea: ${Number(r.skinArea.toPrecision(7))},
  volume: ${Number(r.volume.toPrecision(7))},
  refLength: ${hull === 'wren' ? 32 : 0},
  stiff: [${fmt(r.stiff)}],
  zones: [
${B.ZONES.map((z, i) => `    { name: '${z.name}', area: ${Number(r.zoneArea[i].toPrecision(6))}, radius: ${z.radius}, mirror: ${z.mirror} },`).join('\n')}
  ],
  scaleBig: [${fmt(qb.scale)}],
  scaleSmall: [${fmt(qs.scale)}],
  dataBig:
    '${b64(qb.q)}',
  dataSmall:
    '${b64(qs.q)}',
} as const;
`;
await fs.mkdir(outDir, { recursive: true });
const file = path.join(outDir, `${hull}.ts`);
await fs.writeFile(file, src);
console.log(`aero bake ${hull}: ${r.samples} cells, ${(r.ms / 1000).toFixed(2)} s, ${((qb.q.byteLength + qs.q.byteLength) / 1024).toFixed(1)} KB int16, ${(src.length / 1024).toFixed(1)} KB source → ${path.relative(root, file)}`);
