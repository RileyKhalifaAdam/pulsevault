#!/usr/bin/env node
// Bake the dry-structure moments of the seven hulls (SIMULATION.md W3-A item 1) at BUILD time into
// src/data/massPropsBaked.ts (the pass is tools/massPropsBake.ts, bundled for node with esbuild).
//
//   node tools/bake-massprops.mjs              all seven hulls
//   node tools/bake-massprops.mjs --out <dir>  write elsewhere (scratch runs)
//
// When to re-run: after src/data/hullColliders.ts (e.g. wave 3 appending TANK_FAIRINGS), src/data/hullZones.ts or
// damage.ts zoneOfPoint change; tests/massprops.test.ts re-bakes coarsely and fails when the table is stale.
// Not called by build.mjs. The output is deterministic (fixed grid, fixed order).

import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const outDir = path.resolve(arg('--out', path.join(root, 'src/data')));

const { build } = await import('esbuild');
const tmp = path.join(os.tmpdir(), `tidelock-massprops-${process.pid}.mjs`);
await build({
  stdin: { contents: "export * from './tools/massPropsBake';", resolveDir: root, loader: 'ts' },
  bundle: true, platform: 'node', format: 'esm', outfile: tmp, logLevel: 'error',
});
const B = await import(pathToFileURL(tmp).href);
await fs.unlink(tmp).catch(() => {});

const HULLS = ['wren', 'drover', 'magpie', 'shrike', 'albatross', 'caravel', 'halberd'];
const H = 0.1, SPACING = 0.25;
const fmt = (a) => a.map((x) => Number(x.toPrecision(12))).join(', ');
let body = '';
for (const hull of HULLS) {
  const t0 = performance.now();
  const r = B.bakeHull(hull, H, SPACING);
  body += `  ${hull}: {\n    volume: [${fmt(r.volume)}],\n    skin: ${r.skin ? `[\n      ${r.skin.reduce((s, x, i) => s + (i && i % 10 === 0 ? ',\n      ' : i ? ', ' : '') + Number(x.toPrecision(12)), '')}]` : 'null'},\n  },\n`;
  console.log(`${hull}: V ${r.volume[0].toFixed(1)} m³ in ${(performance.now() - t0).toFixed(0)} ms`);
}
const src = `// GENERATED by tools/bake-massprops.mjs from src/data/hullColliders.ts and hullZones.ts — do not edit; re-run the tool.
// Raw moments [V|A, ∫x, ∫y, ∫z, ∫xx, ∫yy, ∫zz, ∫xy, ∫xz, ∫yz] about the craft origin, craft axes, SI:
// volume = the hull compound as a uniform solid (voxels of ${H} m); skin = per HULL_ZONES zone, the exterior skin
// cells (${SPACING} m, tools/aeroBake.ts sampleSkin) — Wren only. Read by src/world/massProps.ts buildMassModel.

export interface HullMoments {
  volume: number[];
  skin: number[] | null;
}

export const HULL_MOMENTS: Record<string, HullMoments> = {
${body}};
`;
await fs.mkdir(outDir, { recursive: true });
await fs.writeFile(path.join(outDir, 'massPropsBaked.ts'), src);
console.log(`wrote ${path.join(outDir, 'massPropsBaked.ts')}`);
